#!/bin/zsh
set -eu
TASK_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP_VERSION="$(cat "$TASK_ROOT/mac-app/VERSION")"
APP="$TASK_ROOT/mac-app/build/Аватар Студия.app"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
xcrun swiftc -O -framework AppKit "$TASK_ROOT/mac-app/Sources/main.swift" -o "$APP/Contents/MacOS/AvatarStudio"
xcrun swiftc -O -framework AppKit "$TASK_ROOT/mac-app/tools/make-icon-vector-v1.swift" -o "$TASK_ROOT/mac-app/build/make-icon"
"$TASK_ROOT/mac-app/build/make-icon" "$TASK_ROOT/mac-app/build/AvatarStudio.iconset"
/usr/bin/iconutil -c icns "$TASK_ROOT/mac-app/build/AvatarStudio.iconset" -o "$APP/Contents/Resources/AvatarStudio.icns"
rm -f "$APP/Contents/Info.plist"
/usr/bin/plutil -create xml1 "$APP/Contents/Info.plist"
/usr/bin/plutil -insert CFBundleExecutable -string AvatarStudio "$APP/Contents/Info.plist"
/usr/bin/plutil -insert CFBundleIdentifier -string org.avatarstudio.desktop "$APP/Contents/Info.plist"
/usr/bin/plutil -insert CFBundleName -string 'Аватар Студия' "$APP/Contents/Info.plist"
/usr/bin/plutil -insert CFBundleIconFile -string AvatarStudio "$APP/Contents/Info.plist"
/usr/bin/plutil -insert CFBundleShortVersionString -string "$APP_VERSION" "$APP/Contents/Info.plist"
/usr/bin/plutil -insert CFBundleVersion -string 9 "$APP/Contents/Info.plist"
/usr/bin/plutil -insert NSHighResolutionCapable -bool true "$APP/Contents/Info.plist"
/usr/bin/plutil -insert AvatarProjectRoot -string "$TASK_ROOT" "$APP/Contents/Info.plist"
/usr/bin/codesign --force --sign - "$APP"
echo "$APP"
